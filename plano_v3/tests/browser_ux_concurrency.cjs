const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/jeanm/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1366,height:1000}});
  const page=await context.newPage(), other=await context.newPage();
  const base='http://127.0.0.1:5057';
  const get=async path=>(await context.request.get(base+'/api'+path)).json();
  assert.match((await get('/diagnostics')).path,/verification.*ux-/);
  assert.equal(await get('/timer'),null);
  const subject=(await get('/subjects'))[0];
  await page.goto(base+'/?subject='+subject.id);
  await page.waitForFunction(()=>!document.querySelector('[data-topic]').disabled);
  await page.route('**/api/timer',route=>route.request().method()==='POST'?route.fulfill({status:200,json:{bad:true}}):route.continue());
  await page.locator('#start-button').click();
  await page.locator('#timer-error').filter({hasText:'Não foi possível confirmar'}).waitFor();
  assert.equal(await get('/timer'),null);
  await page.unroute('**/api/timer');
  await other.goto(base+'/subjects');
  await page.locator('#start-button').click();
  await page.locator('[data-action=pause]').waitFor();
  await other.locator('.active-session').filter({hasText:'Estudo em andamento'}).waitFor();
  await page.waitForTimeout(1100);
  await page.locator('[data-action=pause]').click();
  await other.locator('.active-session').filter({hasText:'Estudo pausado'}).waitFor();
  const before=await get('/timer');
  await other.goto(base+'/');
  await other.locator('[data-action=resume]').click();
  await page.locator('[data-action=pause]').waitFor();
  assert.equal((await get('/timer')).id,before.id);
  await page.locator('[data-action=finish]').click();
  await page.getByRole('button',{name:'Salvar sessão',exact:true}).click();
  await page.locator('#common-dialog').waitFor({state:'hidden'});
  await other.locator('.active-session').waitFor({state:'hidden'});
  assert.equal(await get('/timer'),null);
  // Manual entry and a note-only correction preserve a topic and its session type.
  const topic=(await get('/topics'))[0];
  await page.locator('#manual-session').click();
  await page.locator('#common-dialog [name=subject_id]').selectOption(String(topic.subject_id));
  await page.locator('#common-dialog [data-topic]').selectOption(String(topic.id));
  await page.locator('#common-dialog [data-kind]').selectOption('review');
  await page.locator('#common-dialog [name=minutes]').fill('25');
  await page.getByRole('button',{name:'Salvar estudo',exact:true}).click();
  await page.locator('#common-dialog').waitFor({state:'hidden'});
  const manual=(await get('/sessions/recent'))[0];
  assert.equal(manual.topic_id,topic.id);assert.equal(manual.session_kind,'review');assert.equal(manual.effective_seconds,1500);
  await page.goto(base+'/analytics?topic_id='+topic.id);
  await page.waitForFunction(()=>document.querySelector('#analytics-results').getAttribute('aria-busy')==='false');
  await page.locator('#breakdown').selectOption('topic');
  await page.screenshot({path:'docs/ux-analytics.png',fullPage:true});
  fs.writeFileSync('docs/ux-concurrency.json',JSON.stringify({two_tabs:true,malformed_timer_response_rejected:true,manual_topic_review:true},null,2));
  console.log('Two tabs, malformed timer response and manual topic review passed.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
