// Explicitly isolated QA database; never use the personal port/database.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/jeanm/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = 'http://127.0.0.1:5057';
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const context = await browser.newContext({viewport:{width:1366,height:1000}});
  const page = await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const request=context.request;
  async function get(path) {const r=await request.get(base+'/api'+path);assert.equal(r.status(),200);return r.json();}
  async function post(path,data) {const r=await request.post(base+'/api'+path,{data});assert.equal(r.status(),200,await r.text());return r.json();}
  const diagnosis=await get('/diagnostics');
  assert.match(diagnosis.path,/verification.*ux-/);
  assert.equal((await get('/courses')).length,0,'Requires a fresh QA fixture');
  const course=await post('/courses',{name:'Computação UX'});
  const subject=await post('/subjects',{course_id:course.id,name:'Linguagens de Programação',academic_status:'available'});
  const other=await post('/subjects',{course_id:course.id,name:'Circuitos',academic_status:'available'});
  await page.goto(base+'/?subject='+subject.id);
  await page.waitForFunction(()=>document.querySelector('#today-subject').value!=='');
  await page.locator('#today-search').fill('programacao');
  assert.equal(await page.locator('#today-subject option').count(),3);
  await page.locator('#start-topics [data-topic]').selectOption('new');
  await page.locator('#start-topics [data-topic-name]').fill('Ponteiros em C');
  await page.locator('#start-button').click();
  await page.locator('[data-action=pause]').waitFor();
  const first=await get('/timer');
  assert.ok(first.topic_id);
  await page.waitForTimeout(1100);
  await page.locator('[data-action=pause]').click();
  await page.locator('[data-action=resume]').waitFor();
  await page.reload();
  await page.locator('[data-action=resume]').waitFor();
  assert.equal((await get('/timer')).id,first.id);
  await page.goto(base+'/subjects');
  await page.locator('.active-session').filter({hasText:'Estudo pausado'}).waitFor();
  assert.match(await page.locator('.active-session').innerText(),/Ponteiros em C/);
  await page.goto(base+'/analytics');
  await page.locator('.active-session').filter({hasText:'Estudo pausado'}).waitFor();
  await page.locator('.active-session').click();
  await page.locator('[data-action=resume]').click();
  await page.locator('[data-action=pause]').waitFor();
  await page.waitForTimeout(1100);
  await page.locator('[data-action=finish]').click();
  await page.locator('#common-dialog [name=completed]').selectOption('true');
  await page.locator('#common-dialog [name=needs_review]').selectOption('true');
  await page.locator('#common-dialog [name=note]').fill('Exercícios sobre ponteiros.');
  await page.getByRole('button',{name:'Salvar sessão',exact:true}).click();
  await page.locator('#common-dialog').waitFor({state:'hidden'});
  assert.equal(await get('/timer'),null);
  assert.equal(await page.locator('.active-session').isVisible(),false);
  let topic=(await get('/topics'))[0];
  assert.equal(topic.completed,1);assert.equal(topic.needs_review,1);
  await page.goto(base+'/subjects?course='+course.id);
  const status=page.locator(`[data-status-id="${subject.id}"]`);
  await status.selectOption('completed');
  await page.locator('#notifications').filter({hasText:'Situação salva'}).waitFor();
  await page.reload();
  await page.waitForFunction(id=>document.querySelector(`[data-status-id="${id}"]`)?.value==='completed',subject.id);
  const statusRoute=`**/api/subjects/${subject.id}`;
  await page.route(statusRoute,route=>route.request().method()==='PATCH'?route.fulfill({status:503,json:{error:'Falha simulada ao salvar.'}}):route.continue());
  await status.selectOption('failed');
  await page.locator('#notifications').filter({hasText:'Falha simulada'}).waitFor();
  assert.equal(await status.inputValue(),'completed');
  assert.equal((await get('/subjects')).find(s=>s.id===subject.id).academic_status,'completed');
  await page.unroute(statusRoute);
  await page.route(statusRoute,route=>route.request().method()==='PATCH'?route.fulfill({status:200,json:{unexpected:true}}):route.continue());
  await status.selectOption('failed');
  await page.locator('#notifications').filter({hasText:'Resposta inesperada'}).waitFor();
  assert.equal(await status.inputValue(),'completed');
  await page.unroute(statusRoute);
  await page.locator('[data-review-topics]').click();
  await page.getByRole('link',{name:'Revisar',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[data-kind]')?.value==='review');
  await page.locator('#start-button').click();
  await page.locator('[data-action=pause]').waitFor();
  const second=await get('/timer');assert.notEqual(second.id,first.id);assert.equal(second.topic_id,first.topic_id);
  assert.equal(second.session_kind,'review');
  await page.screenshot({path:'docs/ux-today.png',fullPage:true});
  await page.waitForTimeout(1100);
  await page.locator('[data-action=finish]').click();
  await page.locator('#common-dialog [name=needs_review]').selectOption('false');
  await page.getByRole('button',{name:'Salvar sessão',exact:true}).click();
  await page.locator('#common-dialog').waitFor({state:'hidden'});
  topic=(await get('/topics'))[0];assert.equal(topic.completed,1);assert.equal(topic.needs_review,0);assert.equal(topic.sessions,2);
  await page.goto(base+'/subjects?course='+course.id);
  await page.locator(`[data-topics="${subject.id}"]`).click();
  await page.locator('[data-add-topic] input').fill('Funções em C');
  await page.locator('[data-create-topic]').click();
  await page.locator('.topic-item').filter({hasText:'Funções em C'}).waitFor();
  const completed=page.locator(`[data-topic-id="${topic.id}"][data-field=completed]`);
  assert.equal(await completed.isChecked(),true);
  await page.locator('#common-dialog [data-close]').first().click();
  await page.screenshot({path:'docs/ux-subjects.png',fullPage:true});
  await page.goto(base+'/analytics');
  await page.waitForFunction(()=>document.querySelector('#analytics-results').getAttribute('aria-busy')==='false');
  assert.match(await page.locator('#history-body').innerText(),/Sessão antiga sem tópico/);
  assert.match(await page.locator('#history-body').innerText(),/Tipo não informado/);
  assert.match(await page.locator('#history-body').innerText(),/Ponteiros em C/);
  await page.locator('[name=topic_id]').selectOption(String(topic.id));
  await page.getByRole('button',{name:'Aplicar filtros'}).click();
  await page.waitForFunction(()=>document.querySelector('#page-info').textContent.includes('2 sessões'));
  await page.locator('#breakdown').selectOption('topic');
  await page.screenshot({path:'docs/ux-analytics.png',fullPage:true});
  const download=page.waitForEvent('download');await page.locator('#export-csv').click();
  const exported=await download;assert.equal(await exported.failure(),null);
  const data=await get('/analytics?topic_id='+topic.id);
  for(const key of ['by_day','by_subject','by_course','by_topic']) assert.equal(data[key].reduce((sum,r)=>sum+r.effective_seconds,0),data.summary.period.effective_seconds);
  // Correction keeps topic and timing unless explicitly edited.
  await page.locator('#history-body [data-edit]').first().click();
  await page.locator('#common-dialog [data-topic]').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('#common-dialog [data-topic]').disabled);
  assert.equal(await page.locator('#common-dialog [data-topic]').inputValue(),String(topic.id));
  await page.locator('#common-dialog [name=note]').fill('Revisão conferida.');
  await page.locator('#common-dialog [name=reason]').fill('Detalhar anotação');
  await page.getByRole('button',{name:'Salvar correção'}).click();
  await page.locator('#common-dialog').waitFor({state:'hidden'});
  assert.equal((await get('/topics')).find(t=>t.id===topic.id).effective_seconds,topic.effective_seconds);
  // The actual prepared files run through the unchanged interpreter.
  const folder='C:/Users/jeanm/OneDrive/Desktop/dowloads/Grades_prontas_para_importar/';
  const imports=[];
  for(const [filename,count] of [['Eletrotecnica.xlsx',26],['Engenharia_Eletrica.xlsx',19],['Engenharia_Computacao.xlsx',19]]) {
    const c=await post('/courses',{name:'Importação '+filename});
    await page.goto(base+'/subjects?course='+c.id);
    await page.locator('[data-import]').first().click();
    await page.locator('#import-dialog [name=file]').setInputFiles(folder+filename);
    await page.getByRole('button',{name:'Ler grade'}).click();
    await page.locator('#confirm-import').waitFor();
    assert.equal(await page.locator('.import-row').count(),count);
    assert.equal(await page.locator('.import-detail[open]').count(),0);
    assert.equal((await get('/subjects?course_id='+c.id)).length,0);
    await page.locator('.import-detail summary').first().click();
    await page.locator('#confirm-import').click();
    await page.locator('#import-dialog').waitFor({state:'hidden'});
    assert.equal((await get('/subjects?course_id='+c.id)).length,count);
    imports.push({filename,count});
  }
  // Transient invalid response cannot look like a saved/confirmed session state.
  await page.route('**/api/timer',route=>route.fulfill({status:200,body:'not json'}));
  await page.goto(base+'/analytics');
  await page.locator('.active-session').filter({hasText:'Não foi possível conferir'}).waitFor();
  await page.unroute('**/api/timer');
  assert.equal(errors.length,0,errors.join('\n'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  fs.writeFileSync('docs/ux-browser.json',JSON.stringify({flows:['A','B','C','D','E','F','G','H','I'],imports,errors,topic,first_timer:first.id,review_timer:second.id},null,2));
  console.log('UX desktop A–I passed; 3 grades imported; no JavaScript errors.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
