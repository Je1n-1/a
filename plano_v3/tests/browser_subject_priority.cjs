const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('C:/Users/jeanm/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base='http://127.0.0.1:5058';
const out=path.join(process.env.LOCALAPPDATA,'PlanoV3/verification/subject-priority-20261016');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  const request=async(method,p,data)=>{const r=await context.request[method](base+'/api'+p,{data});assert.equal(r.status(),200,await r.text());return r.json();};
  const get=p=>request('get',p),post=(p,d)=>request('post',p,d);
  assert.match((await get('/diagnostics')).path,/verification.*subject-priority-20261016/);
  try {
    const course=await post('/courses',{name:'Elétrica '+Date.now()});
    const other=await post('/courses',{name:'Outro curso '+Date.now()});
    const create=(name,academic_status,course_id=course.id)=>post('/subjects',{name,academic_status,course_id});
    const completed=await create('Álgebra','completed');
    const progress=await create('Circuitos','in_progress');
    const review=await create('Proteção','completed');
    const available=await create('Instalações','available');
    await create('Automação','in_progress',other.id);
    const topic=await post('/topics',{subject_id:review.id,name:'Disjuntores'});
    await request('patch','/topics/'+topic.id,{version:topic.version,needs_review:true,completed:true});
    await page.goto(base);
    await page.locator('[data-suggest]').waitFor();
    await page.locator('#today-course').selectOption(String(course.id));
    const groups=await page.locator('#today-subject optgroup').evaluateAll(nodes=>nodes.map(n=>({label:n.label,ids:[...n.children].map(o=>o.value)})));
    assert.deepEqual(groups.map(g=>g.label.replace(/ \(\d+\)$/,'')),['Em andamento','Para revisar','Concluídas','Outras disciplinas']);
    assert.deepEqual(groups.map(g=>g.ids),[[String(progress.id)],[String(review.id)],[String(completed.id)],[String(available.id)]]);
    assert.equal(await page.locator('[data-suggest]').getAttribute('data-suggest'),String(progress.id));
    assert.equal(await page.locator('#today-subject').inputValue(),'');
    await page.locator('[data-suggest]').click();
    assert.equal(await page.locator('#today-subject').inputValue(),String(progress.id));
    assert.equal(await get('/timer'),null);
    await page.locator('#today-search').fill('protecao');
    assert.equal(await page.locator('#today-subject optgroup').count(),1);
    assert.match(await page.locator('#today-subject optgroup').getAttribute('label'),/Para revisar/);
    assert.equal(await page.locator('[data-suggest]').getAttribute('data-suggest'),String(review.id));
    await page.locator('#today-search').fill('algebra');
    assert.match(await page.locator('#today-subject optgroup').getAttribute('label'),/Concluídas/);
    assert.equal(await page.locator('[data-suggest]').getAttribute('data-suggest'),String(completed.id));
    await page.locator('#today-search').fill('não existe');
    assert.equal(await page.locator('#subject-suggestion').isVisible(),false);
    assert.match(await page.locator('#subject-choice-help').innerText(),/Nenhuma disciplina/);
    await page.locator('#today-subject').selectOption('free');
    assert.equal(await page.locator('#free-title').isVisible(),true);
    await page.goto(base+`/?subject=${review.id}&topic=${topic.id}&kind=review`);
    await page.waitForFunction(id=>document.querySelector('[data-topic]').value===id,String(topic.id));
    assert.equal(await page.locator('#today-subject').inputValue(),String(review.id));
    assert.equal(await page.locator('[data-kind]').inputValue(),'review');
    assert.equal(await page.locator('#subject-suggestion').isVisible(),false);
    await page.goto(base);
    await page.locator('[data-suggest]').waitFor();
    await page.locator('#today-course').selectOption(String(course.id));
    await page.screenshot({path:out+'/today-priority.png'});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.locator('#subject-suggestion').scrollIntoViewIfNeeded();
    await page.screenshot({path:out+'/today-priority-mobile.png'});
    assert.deepEqual(errors,[]);
    fs.writeFileSync(out+'/browser.json',JSON.stringify({passed:true,groups,errors,timerUnchanged:true},null,2));
    console.log(JSON.stringify({passed:true,groups,errors}));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});

